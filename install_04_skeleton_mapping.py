class InstallError(RuntimeError):
    pass


def project_root(value: str | None) -> Path:
    root = Path(value).expanduser().resolve() if value else Path.cwd().resolve()
    needed = ("scripts/fighter_model.gd", "scripts/motion_layer.gd", "data/roster.json", "project.godot")
    missing = [name for name in needed if not (root / name).is_file()]
    if missing:
        raise InstallError("Run from your Godot project folder; missing " + ", ".join(missing))
    return root


def text_file(root: Path, rel: str) -> str:
    return (root / rel).read_text(encoding="utf-8-sig")


def extract_profile(path: Path) -> dict:
    item = {"file": path.name, "status": "invalid", "vrm_version": "unknown", "bones": {},
            "bone_count": 0, "warnings": [], "errors": []}
    try:
        with path.open("rb") as fh:
            header = fh.read(20)
            if len(header) != 20:
                raise ValueError("Truncated GLB/VRM header")
            magic, version, total, jlen, jtype = struct.unpack("<4sIIII", header)
            if magic != b"glTF" or version != 2 or jtype != 0x4E4F534A:
                raise ValueError("Not a binary glTF 2.0 VRM file")
            if total != path.stat().st_size or jlen > 32 * 1024 * 1024 or jlen + 20 > total:
                raise ValueError("Invalid GLB length or JSON chunk size")
            doc = json.loads(fh.read(jlen).rstrip(b"\x00 \n\r\t").decode("utf-8"))
        nodes = doc.get("nodes", [])
        item["bone_count"] = sum(len(x.get("joints", [])) for x in doc.get("skins", []))
        exts = doc.get("extensions", {})
        if "VRMC_vrm" in exts:
            item["vrm_version"] = "1.0"
            src = exts["VRMC_vrm"].get("humanoid", {}).get("humanBones", {})
            pairs = [(name, obj.get("node")) for name, obj in src.items() if isinstance(obj, dict)]
        elif "VRM" in exts:
            item["vrm_version"] = "0.x"
            src = exts["VRM"].get("humanoid", {}).get("humanBones", [])
            pairs = [(obj.get("bone"), obj.get("node")) for obj in src if isinstance(obj, dict)]
        else:
            raise ValueError("Missing VRM humanoid extension (VRM/VRMC_vrm)")
        for role, idx in pairs:
            if not isinstance(role, str) or not isinstance(idx, int) or idx < 0 or idx >= len(nodes):
                item["warnings"].append("Invalid humanoid bone reference: " + str(role))
                continue
            canonical = role[0].upper() + role[1:]
            gltf_name = str(nodes[idx].get("name", ""))
            if not gltf_name:
                item["warnings"].append("Unnamed glTF node for " + canonical + " (importer naming expected)")
            item["bones"][canonical] = gltf_name
        item["missing_required"] = [name for name in MANDATORY if name not in item["bones"]]
        item["missing_fingers"] = [name for name in FINGER_NAMES if name not in item["bones"]]
        if item["missing_required"]:
            item["warnings"].append("Missing required humanoid roles: " + ", ".join(item["missing_required"]))
        if item["missing_fingers"]:
            item["warnings"].append("Finger-based grips unavailable for: " + ", ".join(item["missing_fingers"]))
        item["status"] = "ok" if not item["missing_required"] else "incomplete"
    except (OSError, UnicodeError, ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
        item["errors"].append(str(exc))
    return item


def replace_exact(source: str, needle: str, updated: str, label: str) -> str:
    count = source.count(needle)
    if count != 1:
        raise InstallError("scripts/fighter_model.gd changed unexpectedly (" + label + ", count=" + str(count) + "). Refusing unsafe patch.")
    return source.replace(needle, updated, 1)


def patch_model(original: str) -> str:
    if "# FRG04 - rig mapper integrated" in original:
        # A repeat installation does not re-inject methods. Keep any later user changes.
        if "FighterRig.make_grip" not in original or "FighterRig.profile_for" not in original:
            raise InstallError("Existing update 04 markers found but integration is incomplete")
        return original
    s = original
    s = replace_exact(s, "var skeleton: Skeleton3D\n", "var skeleton: Skeleton3D\nvar rig_profile: Dictionary = {} # FRG04 - rig mapper integrated\n", "skeleton variable")
    s = replace_exact(s, 'vrm = load("res://models/%s.vrm" % id).instantiate()\n',
                      'var vrm_resource: Resource = load("res://models/%s.vrm" % id)\n'
                      '\tif not (vrm_resource is PackedScene):\n'
                      '\t\tvar fallback_id: String = str(FALLBACK.get(look.get("body", "f"), "ember"))\n'
                      '\t\tif fallback_id != id:\n'
                      '\t\t\tid = fallback_id\n'
                      '\t\t\tvrm_resource = load("res://models/%s.vrm" % id)\n'
                      '\tif not (vrm_resource is PackedScene):\n'
                      '\t\tpush_error("Fight Royale: cannot import VRM model or its fallback: " + id)\n'
                      '\t\treturn\n'
                      '\tvrm = (vrm_resource as PackedScene).instantiate()\n', "VRM resource loading")
    s = replace_exact(s, 'skeleton = vrm.find_children("*", "Skeleton3D", true, false)[0]\n',
                      'skeleton = FighterRig.find_skeleton(vrm)\n'
                      '\tif skeleton == null:\n'
                      '\t\tpush_error("Fight Royale: VRM model has no imported Skeleton3D: " + id)\n'
                      '\t\treturn\n'
                      '\trig_profile = FighterRig.profile_for(id)\n', "skeleton setup")
    s = replace_exact(s, '\tmotion.heavy = look.get("body", "f") == "m"\n',
                      '\tmotion.heavy = look.get("body", "f") == "m"\n'
                      '\tmotion.bone_map = FighterRig.runtime_bone_map(skeleton, rig_profile)\n', "motion binding")
    beg = s.find('func _grip(side: String) -> Node3D:\n')
    end = s.find('func _mat(c: String, metal := false) -> StandardMaterial3D:\n', beg)
    if beg < 0 or end < 0 or beg >= end or s[beg:end].count('func _foot(side: String) -> Node3D:') != 1:
        raise InstallError("Could not find the expected grip/foot methods; refusing unsafe patch")
    replacement = ('func _grip(side: String) -> Node3D:\n'
                   '\treturn FighterRig.make_grip(skeleton, side, rig_profile)\n\n'
                   'func _foot(side: String) -> Node3D:\n'
                   '\treturn FighterRig.make_foot(skeleton, side, rig_profile)\n\n')
    return s[:beg] + replacement + s[end:]


def patch_motion(original: str) -> str:
    if "# FRG04 - dynamic humanoid lookups" in original:
        if "func _bone_name(" not in original:
            raise InstallError("MotionLayer update 04 marker exists but helper is missing")
        return original
    s = original
    anchor = 'var heavy := false          ## male fighters: quieter idle\n'
    add = ('var bone_map: Dictionary = {}  # FRG04 - dynamic humanoid lookups\n')
    if s.count(anchor) != 1:
        raise InstallError("scripts/motion_layer.gd layout is different (heavy anchor)")
    s = s.replace(anchor, anchor + add, 1)
    helper_anchor = 'var _scale := 1.0\n'
    helper = ('\nfunc _bone_name(sk: Skeleton3D, wanted: String) -> int:\n'
              '\tvar resolved: String = str(bone_map.get(wanted, wanted))\n'
              '\treturn sk.find_bone(resolved)\n')
    if s.count(helper_anchor) != 1:
        raise InstallError("scripts/motion_layer.gd layout is different (_scale anchor)")
    s = s.replace(helper_anchor, helper_anchor + helper, 1)
    pairs = {
        '_hips = sk.find_bone("Hips")': '_hips = _bone_name(sk, "Hips")',
        '_legs = [sk.find_bone("LeftUpperLeg"), sk.find_bone("RightUpperLeg")]': '_legs = [_bone_name(sk, "LeftUpperLeg"), _bone_name(sk, "RightUpperLeg")]',
        '_chest = sk.find_bone("UpperChest")': '_chest = _bone_name(sk, "UpperChest")\n\tif _chest < 0:\n\t\t_chest = _bone_name(sk, "Chest")',
        '_scale = sk.get_bone_global_rest(_hips).origin.y / 0.84  # web rig hip height was 0.84': '_scale = maxf(absf(sk.get_bone_global_rest(_hips).origin.y) / 0.84, 0.15)',
        'var parent_g := sk.get_bone_global_pose(sk.get_bone_parent(b)).basis.get_rotation_quaternion()':
          'var parent_idx: int = sk.get_bone_parent(b)\n\t\t\tvar parent_g := sk.get_bone_global_pose(parent_idx).basis.get_rotation_quaternion() if parent_idx >= 0 else Quaternion.IDENTITY',
    }
    for old, new in pairs.items():
        if s.count(old) != 1:
            raise InstallError("scripts/motion_layer.gd changed unexpectedly: " + old[:40])
        s = s.replace(old, new, 1)
    return s


def json_bytes(data: object) -> bytes:
    return (json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n").encode("utf-8")


def build_changes(root: Path) -> tuple[dict[str, bytes], dict]:
    roster = json.loads((root / "data/roster.json").read_text(encoding="utf-8-sig"))
    if not isinstance(roster, list):
        raise InstallError("data/roster.json must contain a list")
    models = {}
    for file in sorted((root / "models").glob("*.vrm"), key=lambda p: p.name.lower()):
        key = file.stem.lower()
        if key in models:
            raise InstallError("Ambiguous VRM filenames differing only by case: " + file.name)
        models[key] = extract_profile(file)
    errors = []
    for name, data in models.items():
        errors.extend(name + ": " + x for x in data["errors"])
    if not models:
        errors.append("No .vrm files in models/ — mappings remain empty")
    used = {}
    for fighter in roster:
        if not isinstance(fighter, dict):
            continue
        look = fighter.get("look", {})
        name = str(look.get("vrm", "")).lower()
        used[str(fighter.get("id", "unknown"))] = {
            "requested": name or None,
            "model_exists": name in models,
            "fallback": "rook" if look.get("body") == "m" else "ember"
        }
    report = {"update": UPDATE, "models_scanned": len(models), "fighters_scanned": len(used),
              "valid_models": sum(x["status"] == "ok" for x in models.values()),
              "incomplete_models": sum(x["status"] == "incomplete" for x in models.values()),
              "unreadable_models": sum(x["status"] == "invalid" for x in models.values()),
              "errors": errors, "fighters": used, "models": models,
              "notes": ["Static VRM metadata mapping; does not alter skeleton meshes, bones or weights.",
                        "Imported Godot skeletons can only be confirmed in the engine.",
                        "VRMs added after this update require rerunning this installer.",
                        "Update 05 will refine per-character weapon offsets and orientations."]}
    profile = {"schema": 1, "update": UPDATE, "models": models}
    lines = ["FIGHT ROYALE - RIG MAPPING 04", "Models: %d | complete: %d | incomplete: %d | unreadable: %d" %
             (report["models_scanned"], report["valid_models"], report["incomplete_models"], report["unreadable_models"]),
             "Fighters in roster: " + str(report["fighters_scanned"]), ""]
    for name, data in models.items():
        lines.append("%-22s %-11s %-4s bone roles / %s skin joints" % (name, data["status"], len(data["bones"]), data["bone_count"]))
        for w in data["warnings"]:
            lines.append("   WARNING: " + w)
        for e in data["errors"]:
            lines.append("   ERROR: " + e)
    lines += ["", "WHAT CHANGED", "- Generated res://data/rig_profiles.json from each VRM humanoid map.",
              "- Added runtime canonical/source bone lookups and safer weapon grips.",
              "- Added MotionLayer support for dynamic bone names.",
              "- Added optional in-engine verification: tools/check_rigs_04.gd.",
              "", "No sounds, animation clips or VRM model bytes are changed.",
              "Missing finger bones use approximate wrist-based grips; visual tuning is planned for Update 05.", ""]
    changes = {
        "scripts/rig_mapper.gd": RIG_MAPPER.encode("utf-8"),
        "scripts/fighter_model.gd": patch_model(text_file(root, "scripts/fighter_model.gd")).encode("utf-8"),
        "scripts/motion_layer.gd": patch_motion(text_file(root, "scripts/motion_layer.gd")).encode("utf-8"),
        "tools/check_rigs_04.gd": RIG_CHECK.encode("utf-8"),
        "data/rig_profiles.json": json_bytes(profile),
        "reports/rig_audit_04.json": json_bytes(report),
        "reports/rig_audit_04.txt": ("\n".join(lines)).encode("utf-8"),
    }
    return changes, report


def digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def safe_write(file: Path, content: bytes) -> None:
    file.parent.mkdir(parents=True, exist_ok=True)
    temp = file.with_name(file.name + ".tmp." + uuid.uuid4().hex[:8])
    try:
        temp.write_bytes(content)
        os.replace(temp, file)
    finally:
        if temp.exists():
            temp.unlink()


def install(root: Path, changes: dict[str, bytes], dry_run: bool) -> Path | None:
    modified = {rel: content for rel, content in changes.items()
                if not (root / rel).is_file() or (root / rel).read_bytes() != content}
    for rel in changes:
        print("  %-10s %s" % ("UPDATE" if rel in modified else "unchanged", rel))
    print("Files to update:", len(modified))
    if dry_run:
        print("DRY RUN — no files written")
        return None
    if not modified:
        print("Already up to date — nothing modified")
        return None
    backup = root.parent / (root.name + "_backups") / ("rigs_04_" + datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S") + "_" + uuid.uuid4().hex[:6])
    originals = backup / "originals"
    manifest = {"version": UPDATE, "project": str(root), "files": []}
    for rel, content in modified.items():
        file = root / rel
        existed = file.is_file()
        before = file.read_bytes() if existed else b""
        if existed:
            dest = originals / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(before)
        manifest["files"].append({"path": rel, "existed": existed,
                                  "sha_before": digest(before) if existed else None,
                                  "sha_after": digest(content)})
    (backup / "backup_manifest.json").write_bytes(json_bytes(manifest))
    wrote = []
    try:
        for rel, content in modified.items():
            safe_write(root / rel, content)
            wrote.append(rel)
    except Exception:
        for rel in reversed(wrote):
            before = originals / rel
            if before.is_file():
                safe_write(root / rel, before.read_bytes())
            elif (root / rel).is_file():
                (root / rel).unlink()
        raise
    print("Backups:", backup)
    return backup


def restore(root: Path, folder: str) -> None:
    backup = Path(folder).expanduser().resolve()
    manifest = json.loads((backup / "backup_manifest.json").read_text(encoding="utf-8"))
    if manifest.get("version") != UPDATE or Path(manifest.get("project", "")).resolve() != root:
        raise InstallError("Backup does not belong to Update 04 in this project")
    files = manifest.get("files", [])
    # Validate every backup BEFORE changing any files.
    for item in files:
        rel = Path(item["path"])
        if rel.is_absolute() or ".." in rel.parts:
            raise InstallError("Unsafe path in backup")
        if item["existed"]:
            prev = (backup / "originals" / rel).read_bytes()
            if digest(prev) != item["sha_before"]:
                raise InstallError("Backup file has changed: " + str(rel))
    for item in files:
        rel = Path(item["path"])
        dest = root / rel
        if item["existed"]:
            safe_write(dest, (backup / "originals" / rel).read_bytes())
        elif dest.is_file():
            dest.unlink()
        print("  RESTORED", rel)
    print("Restore complete")


def check_godot(root: Path, exe: str | None) -> int:
    if exe:
        executable = shutil.which(exe) or (str(Path(exe).expanduser()) if Path(exe).is_file() else None)
    else:
        executable = next((p for name in ("godot", "godot4", "Godot_v4.4-stable_win64_console.exe", "Godot_v4.4-stable_win64.exe")
                           if (p := shutil.which(name))), None)
    if not executable:
        print("Godot executable not found in PATH. Open the project in Godot to verify models.")
        return 0
    print("Checking imported skeletons in Godot:", executable)
    try:
        import_result = subprocess.run([executable, "--headless", "--path", str(root), "--editor", "--quit"],
                                       capture_output=True, text=True, timeout=180)
        if import_result.returncode != 0:
            print("Godot import encountered errors:\n" + (import_result.stdout + import_result.stderr)[-4500:])
            return 2
        result = subprocess.run([executable, "--headless", "--path", str(root), "--script", "res://tools/check_rigs_04.gd"],
                                capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.TimeoutExpired) as exc:
        print("Godot validation could not finish:", exc)
        return 2
    print((result.stdout + result.stderr)[-8000:])
    if result.returncode:
        print("WARNING: Godot-side rig checks failed; keep the report and share console errors.")
    return result.returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Fight Royale Godot | Update 04 automatic skeleton mapping")
    parser.add_argument("--project", help="Godot project folder (defaults to current directory)")
    parser.add_argument("--dry-run", action="store_true", help="Show changes without writing files")
    parser.add_argument("--restore", metavar="BACKUP_DIR", help="Undo using a rigs_04 backup")
    parser.add_argument("--check-godot", action="store_true", help="Try headless Godot import and rig checks")
    parser.add_argument("--godot", metavar="EXE", help="Godot executable for --check-godot")
    args = parser.parse_args(argv)
    root = project_root(args.project)
    print("FIGHT ROYALE GODOT - UPDATE 04 | SKELETON MAPPING\nProject:", root)
    if args.restore:
        restore(root, args.restore)
        return 0
    changes, report = build_changes(root)
    print("VRMs:", report["models_scanned"], "complete:", report["valid_models"],
          "incomplete:", report["incomplete_models"], "unreadable:", report["unreadable_models"])
    install(root, changes, args.dry_run)
    if not args.dry_run:
        print("Report:", root / "reports/rig_audit_04.txt")
        print("DONE - Runtime bone mapping and safer attachments installed; no VRMs changed.")
    if args.check_godot and not args.dry_run:
        return check_godot(root, args.godot)
    print("Next: Update 05 will tune weapon grips and offsets. Test your character poses in Godot first.")
    return 0


