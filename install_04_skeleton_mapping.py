RIG_MAPPER = r'''# Generated by install_04_skeleton_mapping.py | Fight Royale Godot
class_name FighterRig
extends RefCounted
## Resolves imported VRM humanoid bones WITHOUT changing their skin or hierarchy.
## Godot's VRM importer usually normalizes to LeftHand, RightHand, etc.;
## we also accept source GLB names for importer/version differences.

const PROFILE_PATH := "res://data/rig_profiles.json"
const BONES := ["Hips", "Spine", "Chest", "UpperChest", "Neck", "Head",
    "LeftShoulder", "RightShoulder", "LeftUpperArm", "RightUpperArm",
    "LeftLowerArm", "RightLowerArm", "LeftHand", "RightHand",
    "LeftUpperLeg", "RightUpperLeg", "LeftLowerLeg", "RightLowerLeg",
    "LeftFoot", "RightFoot", "LeftIndexProximal", "RightIndexProximal",
    "LeftLittleProximal", "RightLittleProximal", "LeftMiddleProximal", "RightMiddleProximal"]

static func profile_for(model_id: String) -> Dictionary:
    if not FileAccess.file_exists(PROFILE_PATH):
        return {}
    var doc: Variant = JSON.parse_string(FileAccess.get_file_as_string(PROFILE_PATH))
    if doc is Dictionary:
        var profiles: Dictionary = doc.get("models", {})
        var result: Variant = profiles.get(model_id.to_lower(), {})
        if result is Dictionary:
            return result
    return {}

static func find_skeleton(root: Node) -> Skeleton3D:
    if root is Skeleton3D:
        return root as Skeleton3D
    var queue: Array[Node] = [root]
    while not queue.is_empty():
        var node: Node = queue.pop_front()
        for child in node.get_children():
            if child is Skeleton3D:
                return child as Skeleton3D
            queue.push_back(child)
    return null

static func _key(s: String) -> String:
    return s.to_lower().replace("_", "").replace("-", "").replace(" ", "").replace(".", "")

static func name_for(sk: Skeleton3D, role: String, profile: Dictionary = {}) -> String:
    if sk == null:
        return ""
    if sk.find_bone(role) >= 0:
        return role
    var source: Dictionary = profile.get("bones", {})
    var original: String = str(source.get(role, ""))
    if not original.is_empty() and sk.find_bone(original) >= 0:
        return original
    var target_key: String = _key(role)
    var original_key: String = _key(original)
    for i in sk.get_bone_count():
        var candidate: String = sk.get_bone_name(i)
        var candidate_key: String = _key(candidate)
        if candidate_key == target_key or (original_key != "" and candidate_key == original_key):
            return candidate
    return ""

static func runtime_bone_map(sk: Skeleton3D, profile: Dictionary = {}) -> Dictionary:
    var result: Dictionary = {}
    for role in BONES:
        var resolved: String = name_for(sk, role, profile)
        if not resolved.is_empty():
            result[role] = resolved
    return result

static func _rest_point(sk: Skeleton3D, bone: String, hand_inv: Transform3D) -> Vector3:
    if bone.is_empty():
        return Vector3.ZERO
    var idx: int = sk.find_bone(bone)
    if idx < 0:
        return Vector3.ZERO
    return hand_inv * sk.get_bone_global_rest(idx).origin

static func _bone_anchor(sk: Skeleton3D, canonical: String, profile: Dictionary) -> Node3D:
    var found: String = name_for(sk, canonical, profile)
    if found.is_empty():
        push_warning("Fight Royale: " + canonical + " missing; using stationary fallback attachment")
        var holder := Node3D.new()
        holder.name = canonical + "Fallback04"
        sk.add_child(holder)
        return holder
    var attachment := BoneAttachment3D.new()
    attachment.name = canonical + "Attachment04"
    attachment.bone_name = found
    sk.add_child(attachment)
    return attachment

static func make_foot(sk: Skeleton3D, side: String, profile: Dictionary = {}) -> Node3D:
    return _bone_anchor(sk, side + "Foot", profile)

static func make_grip(sk: Skeleton3D, side: String, profile: Dictionary = {}) -> Node3D:
    var hand_name: String = name_for(sk, side + "Hand", profile)
    var anchor: Node3D = _bone_anchor(sk, side + "Hand", profile)
    var grip := Node3D.new()
    grip.name = side + "Grip04"
    anchor.add_child(grip)
    if hand_name.is_empty():
        # No bone exists to follow; placeholder avoids a crash until the model is rigged.
        grip.position = Vector3(-0.45 if side == "Left" else 0.45, 1.05, 0.0)
        return grip
    var hand_idx: int = sk.find_bone(hand_name)
    var inv: Transform3D = sk.get_bone_global_rest(hand_idx).affine_inverse()
    var middle: Vector3 = _rest_point(sk, name_for(sk, side + "MiddleProximal", profile), inv)
    var index: Vector3 = _rest_point(sk, name_for(sk, side + "IndexProximal", profile), inv)
    var little: Vector3 = _rest_point(sk, name_for(sk, side + "LittleProximal", profile), inv)
    var y: Vector3 = middle
    # Wrist-to-hand direction is a reasonable fallback for models with no finger bones.
    if y.length_squared() < 0.000001:
        var forearm: String = name_for(sk, side + "LowerArm", profile)
        if not forearm.is_empty():
            y = -_rest_point(sk, forearm, inv)
    if y.length_squared() < 0.000001:
        y = Vector3.UP
    y = y.normalized()
    var x: Vector3 = index - little
    x -= y * x.dot(y)
    if x.length_squared() < 0.000001:
        var reference: Vector3 = Vector3.FORWARD if absf(y.dot(Vector3.FORWARD)) < 0.9 else Vector3.RIGHT
        x = reference.cross(y)
    x = x.normalized()
    var z: Vector3 = x.cross(y).normalized()
    x = y.cross(z).normalized()
    # +Y follows the fingers, +X crosses the knuckles: right-handed basis.
    var offset: Vector3 = middle * 0.55 if middle.length_squared() > 0.000001 else y * 0.045
    grip.transform = Transform3D(Basis(x, y, z), offset + z * 0.02)
    return grip
'''

